  /* 1月1日からの通し日数（2月29日は2月28日として扱う） */
  function dayOfYear(m, d) {
    return MONTH_START[m - 1] + Math.min(d, m === 2 ? 28 : 31);
  }

  /* 店は東京にあるので、見ている人の国に関係なく東京の日付で計算する */
